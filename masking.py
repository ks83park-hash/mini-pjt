"""개인정보 마스킹 (규칙 기반): 전화번호·이메일·주소(그 밖에 주민등록번호·카드번호)를 가린다.

- 입력: 모델에 보내기 전에 가린다. 모델 입력과 로그에 원문이 남지 않는다.
- 출력: 고객에게 돌려주기 전에 가린다. 모델이 어딘가에서 본 값을 답에 섞어 내보내도 원문이 나가지 않는다.
- 가린 값은 "[전화번호]"처럼 종류만 남긴다. 원문의 일부(끝 4자리 등)도 남기지 않는다.
- 주문번호(ORD-1001), 운송장(TRK-9001), 승인 번호(APV-…), 금액, 날짜는 가리지 않는다. 도구가 그 값으로 조회해야 하기 때문이다.
- 어떤 종류가 몇 건 가려졌는지(counts)만 돌려준다. 가린 원문 값은 돌려주지도, 로그에 남기지도 않는다.
- 정규식 기반이라 모든 표기를 잡지는 못한다 (예: 숫자를 한글로 풀어 쓴 번호, 주소를 줄여 쓴 표기). 첫 방어선이다.
"""
import re

# 적용 순서가 중요하다: 이메일 -> 주민등록번호 -> 카드번호 -> 전화번호 -> 주소
_CITY = r"(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주)(?:특별시|광역시|특별자치시|특별자치도|도|시)?"
_PATTERNS = [
    ("이메일", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+")),
    ("주민등록번호", re.compile(r"(?<!\d)\d{6}[-\s]?[1-4]\d{6}(?!\d)")),
    ("카드번호", re.compile(r"(?<!\d)\d{4}[-\s]\d{4}[-\s]\d{4}[-\s]\d{4}(?!\d)")),
    ("전화번호", re.compile(
        r"(?<!\d)(?:\+?82[-. ]?)?0?1[016789][-. ]?\d{3,4}[-. ]?\d{4}(?!\d)"       # 휴대전화 (+82 표기 포함)
        r"|(?<!\d)0(?:2|[3-6][1-5]|70|80)[-. ]?\d{3,4}[-. ]?\d{4}(?!\d)"          # 지역번호·인터넷전화
    )),
    ("주소", re.compile(
        # 시도 + 시군구 (+ 구) + 도로명/동 + 건물번호 (+ 동·호). 예: 서울시 강남구 테헤란로 123, 성남시 분당구 판교로 235 101동 202호,
        # 마포구 월드컵로 12길 5
        _CITY + r"\s*[가-힣]{1,6}(?:구|군|시)(?:\s*[가-힣]{1,6}(?:구|군))?\s*[가-힣0-9]{1,10}(?:로|길|동|읍|면|리)"
        r"\s*(?:\d{1,4}길\s*)?\d{1,4}(?:-\d{1,4})?(?:\s*\d{1,4}동)?(?:\s*\d{1,4}호)?"
    )),
]


def mask_text(text):
    """(가려진 문장, {종류: 건수})를 돌려준다. 가릴 것이 없으면 원문 그대로, counts는 빈 dict."""
    text = str(text or "")
    counts = {}
    for label, pattern in _PATTERNS:
        text, n = pattern.subn(f"[{label}]", text)
        if n:
            counts[label] = n
    return text, counts
